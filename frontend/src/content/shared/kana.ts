// Complete Kana Data (Hiragana & Katakana) for Nihongo Journey
// Includes Gojuon (46), Dakuten/Handakuten (25), Yoon (33), Mnemonics (EN & BN), Stroke Orders, Examples & Similar Pairs

export type KanaType = 'hiragana' | 'katakana';
export type KanaCategory = 'gojuon' | 'dakuten' | 'handakuten' | 'yoon';

export interface ExampleWord {
  japanese: string;
  reading: string;
  romaji: string;
  english: string;
  bangla: string;
}

export interface KanaCharacter {
  id: string; // e.g. 'h-a', 'k-a'
  character: string; // e.g. 'あ', 'ア'
  romaji: string; // e.g. 'a', 'ka'
  type: KanaType;
  category: KanaCategory;
  row: string; // 'a', 'ka', 'sa', 'ta', 'na', 'ha', 'ma', 'ya', 'ra', 'wa', 'n'
  column: 'a' | 'i' | 'u' | 'e' | 'o' | 'n' | 'combo';
  strokeCount: number;
  strokeHints: string[];
  mnemonicEn: string;
  mnemonicBn: string;
  exampleWord: ExampleWord;
  similarWith?: string[]; // IDs or characters of easily confused kana
}

export interface SimilarKanaPair {
  id: string;
  type: KanaType;
  chars: string[];
  romajis: string[];
  differenceEn: string;
  differenceBn: string;
  tipEn: string;
  tipBn: string;
}

